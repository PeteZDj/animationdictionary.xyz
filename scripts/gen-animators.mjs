// Generates db/seed-animators.sql from data/animators.ts.
// The animation counts mirror data/marketplace.ts EXACTLY (same hash + rank
// assignment) so /api/animators matches the static /army/:username pages.
//
//   node scripts/gen-animators.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = ((h << 5) - h + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

function slugify(input) {
  return input
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const sqlStr = (s) => "'" + String(s).replace(/'/g, "''") + "'";

// ── parse animators ─────────────────────────────────────────────────────────
const animSrc = read("data/animators.ts");
const animRe = /rank:\s*(\d+),\s*alias:\s*"([^"]+)",\s*specialty:\s*"([^"]+)",\s*certified:\s*(true|false)/g;
const animators = [];
let m;
while ((m = animRe.exec(animSrc))) {
  animators.push({ rank: +m[1], alias: m[2], specialty: m[3], certified: m[4] === "true" });
}
if (animators.length === 0) throw new Error("no animators parsed");
const LEN = animators.length;

// ── parse first 60 verb slugs + first 25 noun slugs (file order) ─────────────
const slugRe = /slug\s*:\s*"([^"]+)"/g;
const grab = (src, n) => {
  const out = [];
  let r;
  const re = new RegExp(slugRe.source, "g");
  while ((r = re.exec(src)) && out.length < n) out.push(r[1]);
  return out;
};
const verbSlugs = grab(read("data/verbs.ts"), 60);
const nounSlugs = grab(read("data/nouns.ts"), 25);

const PACK_SUFFIXES = [
  "Ninja Combat Pack", "Knight Bundle", "Parkour Traversal", "Idle Loops Vol. 1",
  "Reaction Pack", "Bird Flight Pack", "Stealth Toolkit", "Locomotion Starter", "Gesture Vocab",
];

// ── replicate marketplace rank assignment → count per rank ───────────────────
const count = new Array(LEN + 1).fill(0);
const bump = (rank) => { count[rank]++; };
verbSlugs.forEach((s) => bump((hash(`anim-${s}`) % LEN) + 1));
nounSlugs.forEach((s) => bump((hash(`model-${s}`) % LEN) + 1));
PACK_SUFFIXES.forEach((suffix) => {
  const seed = hash(suffix);
  bump((seed % LEN) + 1);
  bump(((seed + 7) % LEN) + 1);
});

// ── profile fields (mirror data/profiles.ts) ─────────────────────────────────
const STUDIO_CITIES = [
  "Nairobi, KE", "Toronto, CA", "Lagos, NG", "Berlin, DE", "Austin, US",
  "Seoul, KR", "Lisbon, PT", "Mumbai, IN", "Cape Town, ZA", "Montreal, CA",
];

const lines = [
  "-- seed-animators — generated by scripts/gen-animators.mjs. DO NOT EDIT.",
  "-- Mirrors data/profiles.ts + data/marketplace.ts.",
  "",
];
for (const a of animators) {
  const username = slugify(a.alias);
  const location = STUDIO_CITIES[a.rank % STUDIO_CITIES.length];
  const joined = 2020 + (a.rank % 6);
  const bio =
    `${a.alias} is a barracks-certified member of the Animation 300, specialising in ${a.specialty.toLowerCase()}. ` +
    `Every clip ships game-ready — clean root motion, retarget-safe skeletons, and loops that actually loop.`;
  lines.push(
    "INSERT INTO animator (id, username, alias, rank, specialty, certified, bio, location, joined_year, animations) VALUES (" +
      [
        a.rank,
        sqlStr(username),
        sqlStr(a.alias),
        a.rank,
        sqlStr(a.specialty),
        a.certified ? 1 : 0,
        sqlStr(bio),
        sqlStr(location),
        joined,
        count[a.rank] || 0,
      ].join(", ") +
      ")\nON CONFLICT(id) DO UPDATE SET username=excluded.username, alias=excluded.alias, rank=excluded.rank, specialty=excluded.specialty, certified=excluded.certified, bio=excluded.bio, location=excluded.location, joined_year=excluded.joined_year, animations=excluded.animations;"
  );
}

const total = count.reduce((s, n) => s + n, 0);
writeFileSync(join(root, "db/seed-animators.sql"), lines.join("\n") + "\n");
console.log(`wrote db/seed-animators.sql — ${animators.length} animators, ${total} animation credits`);
